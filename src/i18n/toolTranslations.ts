export function getLocalizedTool(tool: Tool, locale: Locale): Tool {
  const trans = toolTranslations[tool.id];
  if (!trans) return tool;

  return {
    ...tool,
    name: locale === "zh" ? trans.nameZh : trans.nameEn,
    description: locale === "zh" ? trans.descZh : trans.descEn,
    category: locale === "zh" ? trans.categoryZh : trans.categoryEn,
    usage: locale === "zh" ? (trans.usageZh || tool.usage) : (trans.usageEn || tool.usage),
    example: locale === "zh" ? (trans.exampleZh || tool.example) : (trans.exampleEn || tool.example),
  };
}

export function getLocalizedPhase(phase: Phase, locale: Locale): Phase {
  return {
    ...phase,
    name: locale === "zh" ? phase.nameZh || phase.name : phase.name,
    title: locale === "zh" ? phase.titleZh || phase.title : phase.title,
    description: locale === "zh" ? phase.descriptionZh || phase.description : phase.description,
    tools: phase.tools.map((t) => getLocalizedTool(t, locale)),
  };
}
